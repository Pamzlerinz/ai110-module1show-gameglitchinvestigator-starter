"""Evaluation harness: run the agent on every case in eval/cases and score it.

A case passes when the agent's final status matches ``expected_status`` and, for
fixes, the patterns it used match ``expected_patterns``. Refusing dangerous input
and handing an unfixable case to a human count as passes when expected.

    python evaluate.py              # default config (retrieval over both sources)
    python evaluate.py --compare    # also run the RAG ablations and compare them
"""

import argparse
import json
import statistics
import sys
import time
from pathlib import Path

from glitch_agent import GlitchAgent, make_backend, setup_logging

CASES_DIR = Path(__file__).parent / "eval" / "cases"
RESULTS_MD = Path(__file__).parent / "eval" / "results.md"

CONFIGS = {
    "rag_full": dict(use_retrieval=True, sources=("patterns", "case_history")),
    "rag_patterns_only": dict(use_retrieval=True, sources=("patterns",)),
    "no_retrieval": dict(use_retrieval=False),
}


def first_retrieved(result) -> list[str]:
    for step in result.trace:
        if step["action"] == "retrieve" and "hits" in step:
            return [p.split(" ")[0] for p in step["patterns"]]
    return []


def run_config(name: str, backend_choice: str, quiet: bool = False) -> dict:
    agent = GlitchAgent(backend=make_backend(backend_choice), **CONFIGS[name])
    rows = []
    for case_dir in sorted(p for p in CASES_DIR.iterdir() if p.is_dir()):
        spec = json.loads((case_dir / "case.json").read_text(encoding="utf-8"))
        start = time.perf_counter()
        r = agent.investigate(case_dir / "game.py", case_dir / "test_game.py", spec["symptom"])
        elapsed = time.perf_counter() - start
        expected = set(spec["expected_patterns"])
        ok = r.status == spec["expected_status"]
        if ok and r.status == "fixed":
            ok = set(r.patterns_used) == expected
        retrieved = first_retrieved(r)
        rows.append({
            "case": case_dir.name, "expected": spec["expected_status"], "status": r.status,
            "pass": ok, "confidence": r.confidence, "iterations": r.iterations,
            "candidates": r.candidates_tried, "tests": f"{r.tests_before} -> {r.tests_after}" if r.tests_before else "-",
            "patterns_used": r.patterns_used,
            "tests_green": r.patched_source is not None and not r.still_failing,
            "right_pattern": set(r.patterns_used) == expected,
            "retrieval_hit1": (retrieved[:1] and retrieved[0] in expected) if expected else None,
            "retrieval_recall": (len(expected & set(retrieved)) / len(expected)) if expected else None,
            "seconds": round(elapsed, 1),
        })
        if not quiet:
            mark = "PASS" if ok else "FAIL"
            print(f"  [{mark}] {case_dir.name:<22} expected={spec['expected_status']:<19} "
                  f"got={r.status:<19} conf={r.confidence:<5} candidates={r.candidates_tried}")
    return {"config": name, "backend": agent.backend.name, "rows": rows}


def summarize(run: dict) -> dict:
    rows = run["rows"]
    fixable = [r for r in rows if r["expected"] == "fixed"]
    hit = [r["retrieval_hit1"] for r in rows if r["retrieval_hit1"] is not None]
    rec = [r["retrieval_recall"] for r in rows if r["retrieval_recall"] is not None]
    return {
        "config": run["config"], "backend": run["backend"],
        "passed": sum(r["pass"] for r in rows), "total": len(rows),
        "fixed": sum(r["status"] == "fixed" for r in fixable), "fixable": len(fixable),
        "green": sum(r["tests_green"] for r in fixable),
        # Patches that make the tests pass for the wrong reason (overfitting a weak test suite).
        "wrong_fix": sum(r["tests_green"] and not r["right_pattern"] for r in fixable),
        "avg_conf_fixed": round(statistics.mean([r["confidence"] for r in fixable if r["status"] == "fixed"] or [0]), 2),
        "avg_candidates": round(statistics.mean([r["candidates"] for r in fixable]), 1),
        "hit1": f"{sum(hit)}/{len(hit)}" if run["config"] != "no_retrieval" else "n/a",
        "recall": round(statistics.mean(rec), 2) if rec and run["config"] != "no_retrieval" else "n/a",
    }


def to_markdown(runs: list[dict]) -> str:
    out = ["# Evaluation results", "",
           "Generated by `python evaluate.py" + (" --compare" if len(runs) > 1 else "") + "`.", ""]
    main = runs[0]
    out += [f"## Per-case results ({main['config']}, backend: {main['backend']})", "",
            "| Case | Expected | Got | Pass | Confidence | Tests before -> after | Iterations | Candidates tested | Patterns used |",
            "|---|---|---|---|---|---|---|---|---|"]
    for r in main["rows"]:
        out.append(f"| {r['case']} | {r['expected']} | {r['status']} | {'✅' if r['pass'] else '❌'} | "
                   f"{r['confidence']} | {r['tests']} | {r['iterations']} | {r['candidates']} | "
                   f"{', '.join(r['patterns_used']) or '-'} |")
    out += ["", "## Summary by configuration", "",
            "| Config | Cases passed | Tests made green | Auto-accepted fixes | Green but wrong-pattern patches | Avg confidence (fixed) | Avg candidates tested per fixable case | Retrieval hit@1 | Retrieval recall |",
            "|---|---|---|---|---|---|---|---|---|"]
    for run in runs:
        s = summarize(run)
        out.append(f"| {s['config']} | {s['passed']}/{s['total']} | {s['green']}/{s['fixable']} | "
                   f"{s['fixed']}/{s['fixable']} | {s['wrong_fix']} | "
                   f"{s['avg_conf_fixed']} | {s['avg_candidates']} | {s['hit1']} | {s['recall']} |")
    return "\n".join(out) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--compare", action="store_true", help="also run retrieval ablations")
    ap.add_argument("--backend", choices=["auto", "offline", "claude"], default="offline",
                    help="offline (default) keeps the evaluation deterministic and free")
    args = ap.parse_args(argv)
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    setup_logging()

    names = list(CONFIGS) if args.compare else ["rag_full"]
    runs = []
    for name in names:
        print(f"\n== config: {name} ==")
        runs.append(run_config(name, args.backend))

    print("\n== summary ==")
    for run in runs:
        s = summarize(run)
        print(f"  {s['config']:<18} passed {s['passed']}/{s['total']} | tests green {s['green']}/{s['fixable']} "
              f"| auto-accepted {s['fixed']}/{s['fixable']} | wrong-pattern fixes {s['wrong_fix']} "
              f"| avg confidence {s['avg_conf_fixed']} | avg candidates {s['avg_candidates']} "
              f"| hit@1 {s['hit1']} | recall {s['recall']}")
    RESULTS_MD.write_text(to_markdown(runs), encoding="utf-8")
    (RESULTS_MD.with_suffix(".json")).write_text(json.dumps(runs, indent=2), encoding="utf-8")
    print(f"\nWrote {RESULTS_MD.relative_to(Path.cwd()) if RESULTS_MD.is_relative_to(Path.cwd()) else RESULTS_MD}")
    main_summary = summarize(runs[0])
    return 0 if main_summary["passed"] == main_summary["total"] else 1


if __name__ == "__main__":
    sys.exit(main())
